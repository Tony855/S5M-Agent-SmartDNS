// writeAgentWSJSON applies a bounded write deadline to every server-to-Agent
// frame. Without this, a slow or half-open peer can stall command/config handling
// indefinitely and make the control channel appear unresponsive.
func writeAgentWSJSON(conn *websocket.Conn, machineCode string, payload any) error {
	messageType := "unknown"
	switch message := payload.(type) {
	case map[string]any:
		if value, ok := message["type"].(string); ok {
			messageType = value
		}
	case map[string]string:
		if value, ok := message["type"]; ok {
			messageType = value
		}
	}
	if err := conn.SetWriteDeadline(time.Now().Add(5 * time.Second)); err != nil {
		fmt.Printf("agent_ws: set write deadline failed machine_code=%q message_type=%q: %s\n", machineCode, messageType, safeAgentWebSocketError("设置写入超时", err))
		return err
	}
	if err := conn.WriteJSON(payload); err != nil {
		fmt.Printf("agent_ws: write failed machine_code=%q message_type=%q: %s\n", machineCode, messageType, safeAgentWebSocketError("发送消息", err))
		return err
	}
	return nil
}

func sanitizeAgentWebSocketText(value string) string {
	detail := strings.TrimSpace(value)
	// Handle both plain key=value diagnostics and JSON-like quoted fields.
	detail = regexp.MustCompile(`(?i)(["']?(?:secret|token|password|api[_-]?key)["']?\s*[:=]\s*)("[^"\\]*(?:\\.[^"\\]*)*"|'[^'\\]*(?:\\.[^'\\]*)*'|[^"'[:space:],;}{]+)`).ReplaceAllString(detail, "$1\"[已隐藏]\"")
	// Authorization headers commonly carry credentials without a token key.
	detail = regexp.MustCompile(`(?i)(authorization\s*[:=]\s*bearer\s+)[A-Za-z0-9._~+/=-]+`).ReplaceAllString(detail, "$1[已隐藏]")
	detail = regexp.MustCompile(`([A-Za-z]:)?[/\\\\][^[:space:]\\"']+`).ReplaceAllString(detail, "[路径已隐藏]")
	detail = strings.Join(strings.Fields(detail), " ")
	if len(detail) > 600 {
		detail = detail[:600] + "…"
	}
	return detail
}

// sanitizeAgentStatusDiagnostics prevents Agent-provided error details from
// leaking credentials or local paths into persisted status, logs, and browser events.
func sanitizeAgentStatusDiagnostics(status map[string]any) {
	for _, key := range []string{"last_error", "traffic_error", "connections_error"} {
		if value, ok := status[key].(string); ok {
			status[key] = sanitizeAgentWebSocketText(value)
		}
	}
}

func safeAgentWebSocketError(operation string, err error) string {
	detail := "未知错误"
	if err != nil && strings.TrimSpace(err.Error()) != "" {
		detail = sanitizeAgentWebSocketText(err.Error())
	}
	return operation + "失败: " + detail
}

// shouldLogAgentTelemetry rate-limits successful receive diagnostics per Agent.
// It is independent from persistence throttling and never affects telemetry delivery.
func shouldLogAgentTelemetry(now, last time.Time, interval time.Duration) bool {
	return interval > 0 && (last.IsZero() || now.Sub(last) >= interval)
}

func (a *App) handleAgentWebSocket(w http.ResponseWriter, r *http.Request) {
	machineCode, err := a.agentMachineFromRequest(r)
	if err != nil {
		writeErr(w, http.StatusUnauthorized, err.Error())
		return
	}

	conn, err := agentWSUpgrader.Upgrade(w, r, nil)
	if err != nil {
		return // The upgrader has already written the HTTP error response.
	}
	defer conn.Close()

	// Serialize session replacement with per-Agent command delivery/ACK. Without
	// this fence, a new socket could supersede the old generation after the old
	// socket passed its generation check but before it sent a command or persisted
	// an ACK. Keep lock ordering consistent: command lock, then agentWSMu.
	unlockCommand := a.lockAgentWSCommand(machineCode)

	// The credential may have been revoked after the initial JWT check but
	// before the WebSocket upgrade completed. Revalidate under the same lock
	// used by revocation before registering this socket: telemetry intentionally
	// relies on the registered session generation instead of querying SQLite
	// for every frame.
	// The per-Agent lock fences revocation and replacement while this
	// credential lookup runs. Keep SQLite reads outside the global session mutex.
	currentCode, authErr := a.agentMachineFromRequest(r)
	if authErr != nil || currentCode != machineCode {
		unlockCommand()
		closeAgentWebSocket(conn, "Agent binding is no longer authorized")
		return
	}
	a.agentWSMu.Lock()

	// A newly authenticated connection supersedes any older connection for the
	// same Agent. Older sockets may still be blocked in ReadJSON, so every
	// heartbeat must verify its generation before it can mutate persisted state.
	if a.agentWSGeneration == nil {
		a.agentWSGeneration = make(map[string]uint64)
	}
	a.agentWSGeneration[machineCode]++
	generation := a.agentWSGeneration[machineCode]
	if a.agentWSConnections == nil {
		a.agentWSConnections = make(map[string]*agentWSConnection)
	}
	// Detach the previous socket while holding the session mutex, but perform
	// the potentially blocking network close only after releasing the global lock.
	var previousConn *websocket.Conn
	if previous := a.agentWSConnections[machineCode]; previous != nil {
		previousConn = previous.conn
	}
	session := &agentWSConnection{conn: conn}
	a.agentWSConnections[machineCode] = session
	a.agentWSMu.Unlock()
	if previousConn != nil {
		closeAgentWebSocket(previousConn, "Agent connection superseded")
	}
	unlockCommand()
	defer func() {
		a.agentWSMu.Lock()
		if a.agentWSConnections[machineCode] == session {
			delete(a.agentWSConnections, machineCode)
		}
		a.agentWSMu.Unlock()
	}()
	// Keep the generation counter after disconnect to prevent an ABA reuse.

	conn.SetReadLimit(agentWSMaxMessageBytes)
	_ = conn.SetReadDeadline(time.Now().Add(agentWSHeartbeatTTL))
	conn.SetPongHandler(func(string) error {
		return conn.SetReadDeadline(time.Now().Add(agentWSHeartbeatTTL))
	})

	if err := writeAgentWSJSON(conn, machineCode, map[string]any{
		"type":                   "welcome",
		"protocol":               1,
		"heartbeat_interval_sec": 30,
	}); err != nil {
		return
	}

	for {
		var msg agentWSMessage
		if err := conn.ReadJSON(&msg); err != nil {
			if !websocket.IsCloseError(err, websocket.CloseNormalClosure, websocket.CloseGoingAway) {
				fmt.Printf("agent_ws: read failed machine_code=%q: %s\n", machineCode, safeAgentWebSocketError("读取消息", err))
			}
			return
		}
		if msg.Type == "telemetry" {
			if err := validateAgentWSTelemetry(msg.Status); err != nil {
				_ = writeAgentWSJSON(conn, machineCode, map[string]string{"type": "error", "id": msg.ID, "message": err.Error()})
				continue
			}
			sanitizeAgentStatusDiagnostics(msg.Status)
			receivedAt := time.Now()
			telemetry := map[string]any{
				"upload_speed": msg.Status["upload_speed"],
				"download_speed": msg.Status["download_speed"],
				"connections": msg.Status["connections"],
				"upload_total": msg.Status["upload_total"],
				"download_total": msg.Status["download_total"],
				"traffic_error": msg.Status["traffic_error"],
				"connections_error": msg.Status["connections_error"],
				"telemetry_received_at_ms": receivedAt.UnixMilli(),
			}
			if stale, ok := msg.Status["telemetry_stale"].(bool); ok {
				telemetry["telemetry_stale"] = stale
			}
			if sampledAt, ok := msg.Status["telemetry_sampled_at_ms"]; ok {
				telemetry["telemetry_sampled_at_ms"] = sampledAt
			}
			// Serialize persisted state changes per Agent, not globally. Revocation
			// and session replacement take the same per-Agent lock before agentWSMu.
			// This keeps a node's heartbeat/telemetry snapshots ordered while allowing
			// unrelated nodes to proceed during SQLite I/O.
			unlockNode := a.lockAgentWSCommand(machineCode)
			a.agentWSMu.Lock()
			if a.agentWSGeneration[machineCode] != generation || a.agentWSConnections[machineCode] != session {
				a.agentWSMu.Unlock()
				unlockNode()
				return
			}
			// The socket was authenticated at upgrade. Its generation/session
			// identity is the revocation fence; do not hit the credential store
			// for every 200ms telemetry frame. Heartbeats still revalidate tokens.
			// Keep the latest snapshot in the existing status record at most once
			// every 5 seconds.
			if a.agentTelemetryPersistAt == nil {
				a.agentTelemetryPersistAt = make(map[string]time.Time)
			}
			if a.agentTelemetryLogAt == nil {
				a.agentTelemetryLogAt = make(map[string]time.Time)
			}
			shouldPersist := receivedAt.Sub(a.agentTelemetryPersistAt[machineCode]) >= 5*time.Second
			shouldLog := shouldLogAgentTelemetry(receivedAt, a.agentTelemetryLogAt[machineCode], time.Minute)
			if shouldLog {
				a.agentTelemetryLogAt[machineCode] = receivedAt
			}
			if shouldPersist {
				// Throttle failed persistence attempts too; a database outage must
				// not turn every 200ms frame into another database read/write.
				a.agentTelemetryPersistAt[machineCode] = receivedAt
			}
			a.agentWSMu.Unlock()
			if shouldLog {
				fmt.Printf("agent_ws: telemetry received machine_code=%q upload_speed=%v download_speed=%v upload_total=%v download_total=%v connections=%v stale=%v traffic_error=%q connections_error=%q\n",
					machineCode, telemetry["upload_speed"], telemetry["download_speed"], telemetry["upload_total"], telemetry["download_total"], telemetry["connections"], telemetry["telemetry_stale"], telemetry["traffic_error"], telemetry["connections_error"])
			}
			if shouldPersist {
				settings, settingsErr := a.store.GetSettings()
				if settingsErr != nil {
					fmt.Printf("agent_ws: telemetry snapshot read failed machine_code=%q: %s\n", machineCode, safeAgentWebSocketError("读取统计快照", settingsErr))
				} else {
					var saved map[string]any
					raw := strings.TrimSpace(settings["agent_status_"+machineCode])
					if raw != "" {
						if unmarshalErr := json.Unmarshal([]byte(raw), &saved); unmarshalErr != nil {
							fmt.Printf("agent_ws: telemetry snapshot decode failed machine_code=%q: %s\n", machineCode, safeAgentWebSocketError("解析已有统计快照", unmarshalErr))
						}
					}
					if saved == nil {
						saved = make(map[string]any)
					}
					for key, value := range telemetry { saved[key] = value }
					// Persist server receive time separately from the Agent's sample clock
					// so dashboard freshness is not affected by remote clock skew.
					saved["telemetry_received_at_ms"] = receivedAt.UnixMilli()
					payload, marshalErr := json.Marshal(saved)
					if marshalErr != nil {
						fmt.Printf("agent_ws: telemetry snapshot encode failed machine_code=%q: %s\n", machineCode, safeAgentWebSocketError("序列化统计快照", marshalErr))
					} else if updateErr := a.store.UpdateSettings(map[string]string{"agent_status_"+machineCode: string(payload)}); updateErr != nil {
						fmt.Printf("agent_ws: telemetry snapshot persistence failed machine_code=%q: %s\n", machineCode, safeAgentWebSocketError("保存统计快照", updateErr))
					}
				}
			}
			unlockNode()
			a.publishBrowserEvent(map[string]any{"type": "agent.telemetry.updated", "machine_code": machineCode, "received_at_ms": receivedAt.UnixMilli(), "status": telemetry})
			_ = conn.SetReadDeadline(time.Now().Add(agentWSHeartbeatTTL))
			continue
		}
		if msg.Type != "heartbeat" {
			if msg.Type == "config.request" {
				fmt.Printf("agent_ws: config request machine_code=%q id=%q client_sha256=%q\n", machineCode, msg.ID, msg.ConfigHash)
			} else {
				fmt.Printf("agent_ws: request received machine_code=%q type=%q id=%q\n", machineCode, msg.Type, msg.ID)
			}
		}
		if msg.Type == "config.request" || msg.Type == "command.request" || msg.Type == "command.ack" {
			// Serialize each node's operation with revocation, but never hold the
			// process-wide session mutex across credential or configuration DB I/O.
			unlockNode := a.lockAgentWSCommand(machineCode)
			a.agentWSMu.Lock()
			stale := a.agentWSGeneration[machineCode] != generation
			a.agentWSMu.Unlock()
			if stale {
				unlockNode()
				_ = writeAgentWSJSON(conn, machineCode, map[string]string{"type": "error", "id": msg.ID, "message": "Agent WebSocket 连接已被更新连接取代"})
				return
			}
			authorizedCode, authErr := a.agentMachineFromRequest(r)
			if authErr != nil || authorizedCode != machineCode {
				unlockNode()
				_ = writeAgentWSJSON(conn, machineCode, map[string]string{"type": "error", "id": msg.ID, "message": "Agent 未授权或授权已失效"})
				return
			}
			switch msg.Type {
			case "config.request":
				err = a.sendAgentWSConfig(conn, machineCode, msg.ID, msg.ConfigHash, msg.SmartDNSHash)
			case "command.request":
				err = a.sendAgentWSCommand(conn, machineCode, msg.ID)
			case "command.ack":
				err = a.ackAgentWSCommand(machineCode, msg.ID, msg.CommandStatus, msg.Message, msg.Config)
			}
			unlockNode()
			if err != nil {
				operation := "处理 Agent WebSocket 请求"
				if msg.Type == "config.request" {
					operation = "读取节点配置"
				} else if msg.Type == "command.request" {
					operation = "读取待执行命令"
				}
				message := safeAgentWebSocketError(operation, err)
				fmt.Printf("agent_ws: request failed machine_code=%q type=%q id=%q: %s\n", machineCode, msg.Type, msg.ID, message)
				_ = writeAgentWSJSON(conn, machineCode, map[string]string{"type": "error", "id": msg.ID, "message": message})
				continue
			}
			if msg.Type == "command.ack" {
				if err := writeAgentWSJSON(conn, machineCode, map[string]any{"type": "command.acknowledged", "id": msg.ID, "ok": true}); err != nil {
					return
				}
			}
			continue
		}
		if msg.Type != "heartbeat" || msg.Status == nil {
			_ = writeAgentWSJSON(conn, machineCode, map[string]string{"type": "error", "id": msg.ID, "message": "不支持的 WebSocket 消息类型"})
			continue
		}
		if err := validateAgentWSStatus(msg.Status); err != nil {
			_ = writeAgentWSJSON(conn, machineCode, map[string]string{
				"type":    "error",
				"id":      msg.ID,
				"message": err.Error(),
			})
			continue
		}
		sanitizeAgentStatusDiagnostics(msg.Status)
		receivedAt := time.Now()
		msg.Status["received_at"] = receivedAt.Unix()
		payload, marshalErr := json.Marshal(msg.Status)
		if marshalErr != nil {
			return
		}
		now := strconv.FormatInt(receivedAt.Unix(), 10)
		// Serialize this Agent's heartbeat with its telemetry persistence and
		// revocation/session replacement, but never hold the global session mutex
		// while SQLite performs a potentially blocking write.
		unlockNode := a.lockAgentWSCommand(machineCode)
		// Revocation and session replacement also take unlockNode first, so
		// credential lookup can safely happen without holding the global mutex.
		// This avoids blocking unrelated Agents on a SQLite read.
		authorizedCode, authErr := a.agentMachineFromRequest(r)
		a.agentWSMu.Lock()
		if a.agentWSGeneration[machineCode] != generation {
			a.agentWSMu.Unlock()
			unlockNode()
			_ = writeAgentWSJSON(conn, machineCode, map[string]string{
				"type":    "error",
				"id":      msg.ID,
				"message": "Agent WebSocket 连接已被更新连接取代",
			})
			return
		}
		// Revalidate credentials for heartbeats as well as config/command
		// operations. The per-Agent lock fences revocation while this lookup runs.
		if authErr != nil || authorizedCode != machineCode {
			a.agentWSMu.Unlock()
			unlockNode()
			_ = writeAgentWSJSON(conn, machineCode, map[string]string{
				"type":    "error",
				"id":      msg.ID,
				"message": "Agent 未授权或授权已失效",
			})
			return
		}
		if a.agentHeartbeatAt == nil {
			a.agentHeartbeatAt = make(map[string]int64)
		}
		if receivedAt.UnixNano() < a.agentHeartbeatAt[machineCode] {
			a.agentWSMu.Unlock()
			unlockNode()
			_ = writeAgentWSJSON(conn, machineCode, map[string]string{
				"type":    "error",
				"id":      msg.ID,
				"message": "已忽略较旧的 Agent 心跳",
			})
			continue
		}
		a.agentWSMu.Unlock()
		if err := a.store.UpdateSettings(map[string]string{
			"agent_lastseen_" + machineCode: now,
			"agent_status_" + machineCode:   string(payload),
		}); err != nil {
			unlockNode()
			_ = writeAgentWSJSON(conn, machineCode, map[string]string{
				"type":    "error",
				"id":      msg.ID,
				"message": "保存 Agent 心跳失败",
			})
			continue
		}
		a.agentWSMu.Lock()
		a.agentHeartbeatAt[machineCode] = receivedAt.UnixNano()
		a.agentWSMu.Unlock()
		unlockNode()
		a.publishBrowserEvent(map[string]any{"type": "agent.status.updated", "machine_code": machineCode, "last_seen": receivedAt.Unix(), "server_time": time.Now().Unix(), "status": msg.Status})
		_ = conn.SetReadDeadline(time.Now().Add(agentWSHeartbeatTTL))
		if err := writeAgentWSJSON(conn, machineCode, map[string]any{
			"type": "heartbeat.ack",
			"id":   msg.ID,
			"ok":   true,
		}); err != nil {
			return
		}
	}
}

// sendAgentWSConfig returns only the configuration assigned to the authenticated machine.
func (a *App) sendAgentWSConfig(conn *websocket.Conn, machineCode, requestID, clientHash, clientSmartDNSHash string) error {
	nodeConfig, err := a.store.GetNodeConfig(machineCode)
	if err != nil {
		return err
	}
	yml := ""
	if nodeConfig != nil {
		// Preserve the exact persisted bytes for compare-and-swap and hashing.
		// Trimming here makes the expected snapshot differ from the DB value when
		// the YAML has a trailing newline, causing every normalization to conflict.
		yml = nodeConfig.YAML
	}
	if strings.TrimSpace(yml) == "" {
		yml, err = a.BuildConfigForMachine(machineCode)
		if err != nil {
			return err
		}
	}
	// Repair stale persisted node configs before hashing/sending; otherwise the Agent
	// would keep receiving the controller's local listener configuration instead of the Agent's transparent-only configuration.
	normalized, normalizeErr := normalizeAgentProxyConfig(yml)
	if normalizeErr != nil {
		return normalizeErr
	}
	if normalized != yml {
		updated, saveErr := a.store.SaveNodeConfigIfUnchanged(machineCode, yml, normalized)
		if saveErr != nil {
			return saveErr
		}
		if updated {
			yml = normalized
		} else {
			// A concurrent operator save is newer than this normalization snapshot.
			latest, readErr := a.store.GetNodeConfig(machineCode)
			if readErr != nil {
				return readErr
			}
			if latest == nil || strings.TrimSpace(latest.YAML) == "" {
				return fmt.Errorf("并发更新后节点配置不存在")
			}
			// A concurrent operator edit may itself reintroduce an unpublished
			// proxy listener. Never send that snapshot without re-validating it.
			latestNormalized, latestNormalizeErr := normalizeAgentProxyConfig(latest.YAML)
			if latestNormalizeErr != nil {
				return fmt.Errorf("并发更新后的节点配置规范化失败: %w", latestNormalizeErr)
			}
			if latestNormalized != latest.YAML {
				return fmt.Errorf("节点配置在规范化期间发生并发更新；为避免下发未规范化配置，请重试同步")
			}
			yml = latest.YAML
		}
	}

	// Keep config publication and explicit apply commands behind one identical per-client ingress gate.
	if err := a.requireSmartDNSIngressReady(machineCode); err != nil {
		return err
	}

	// SmartDNS is a runtime capability, not part of the saved node configuration.
	// Apply it only to the outgoing payload so health loss immediately falls back
	// to the original configured nameservers on the next config request.
	domesticListener, domesticReported := a.agentSmartDNSDomesticListenerStatus(machineCode)
	if domesticReported {
		yml, err = applyAgentRuntimeDNS(yml, a.agentHasHealthySmartDNS(machineCode), domesticListener)
	} else {
		yml, err = applyAgentRuntimeDNS(yml, a.agentHasHealthySmartDNS(machineCode))
	}
	if err != nil {
		return err
	}
	sum := sha256.Sum256([]byte(yml))
	hash := hex.EncodeToString(sum[:])
	// A controller-managed SmartDNS document participates in the same
	// compare-and-sync decision as Mihomo. If no managed document exists,
	// preserve the legacy Agent-local SmartDNS behavior.
	smartDNSYAML, smartDNSErr := a.store.GetSetting("smartdns_config_" + machineCode)
	if smartDNSErr != nil && smartDNSErr != sql.ErrNoRows {
		return fmt.Errorf("读取主控端 SmartDNS 配置失败: %w", smartDNSErr)
	}
	if smartDNSErr == sql.ErrNoRows {
		smartDNSYAML = ""
	}
	if len(smartDNSYAML) > 8<<10 {
		return fmt.Errorf("主控端 SmartDNS 配置超过 8 KiB 限制")
	}
	smartDNSHash := ""
	if strings.TrimSpace(smartDNSYAML) != "" {
		smartSum := sha256.Sum256([]byte(smartDNSYAML))
		smartDNSHash = hex.EncodeToString(smartSum[:])
	}
	if err := a.store.UpdateSettings(map[string]string{"agent_lastseen_" + machineCode: strconv.FormatInt(time.Now().Unix(), 10)}); err != nil {
		return err
	}
	if clientHash == hash && (smartDNSHash == "" || clientSmartDNSHash == smartDNSHash) {
		if err := writeAgentWSJSON(conn, machineCode, map[string]any{
			"type": "config.unchanged", "id": requestID, "sha256": hash,
			"smartdns_sha256": smartDNSHash,
		}); err != nil {
			return fmt.Errorf("发送配置未变更确认失败: %w", err)
		}
		fmt.Printf("agent_ws: config unchanged machine_code=%q request_id=%q sha256=%s smartdns_sha256=%s\n", machineCode, requestID, hash, smartDNSHash)
		return nil
	}
	payload := map[string]any{"type": "config.sync", "id": requestID, "sha256": hash, "yaml": yml}
	if smartDNSHash != "" {
		payload["smartdns_sha256"] = smartDNSHash
		payload["smartdns_yaml"] = smartDNSYAML
	}
	if err := writeAgentWSJSON(conn, machineCode, payload); err != nil {
		return fmt.Errorf("发送配置失败: %w", err)
	}
	fmt.Printf("agent_ws: config delivered machine_code=%q request_id=%q bytes=%d sha256=%s smartdns_bytes=%d smartdns_sha256=%s\n", machineCode, requestID, len(yml), hash, len(smartDNSYAML), smartDNSHash)
	return nil
}

// sendAgentWSCommand redelivers the persisted pending command until an ACK is stored.
// lockAgentWSCommand serializes commands for one Agent while allowing
// unrelated nodes to execute and acknowledge commands concurrently.
type agentWSCommandLock struct {
	mu   sync.Mutex
	refs int
}

// lockAgentWSCommand serializes commands for one Agent while allowing unrelated
// Agents to proceed independently. References include both holders and waiters,
// so an idle lock can be safely removed without splitting a node's lock domain.
func (a *App) lockAgentWSCommand(machineCode string) func() {
	a.agentWSCommandMu.Lock()
	if a.agentWSCommandLocks == nil {
		a.agentWSCommandLocks = make(map[string]*agentWSCommandLock)
	}
	lock := a.agentWSCommandLocks[machineCode]
	if lock == nil {
		lock = &agentWSCommandLock{}
		a.agentWSCommandLocks[machineCode] = lock
	}
	lock.refs++
	a.agentWSCommandMu.Unlock()

	lock.mu.Lock()
	return func() {
		lock.mu.Unlock()
		a.agentWSCommandMu.Lock()
		lock.refs--
		if lock.refs == 0 && a.agentWSCommandLocks[machineCode] == lock {
			delete(a.agentWSCommandLocks, machineCode)
		}
		a.agentWSCommandMu.Unlock()
	}
}

func (a *App) sendAgentWSCommand(conn *websocket.Conn, machineCode, requestID string) error {
	settings, err := a.store.GetSettings()
	if err != nil {
		return err
	}
	raw := strings.TrimSpace(settings["agent_command_"+machineCode])
	if raw == "" {
		return writeAgentWSJSON(conn, machineCode, map[string]any{"type": "command.none", "id": requestID})
	}
	var command map[string]any
	if err := json.Unmarshal([]byte(raw), &command); err != nil {
		return fmt.Errorf("解析待执行命令失败: %w", err)
	}
	if err := writeAgentWSJSON(conn, machineCode, map[string]any{"type": "command.deliver", "id": requestID, "command": command}); err != nil {
		return fmt.Errorf("发送待执行命令失败: %w", err)
	}
	fmt.Printf("agent_ws: command delivered machine_code=%q request_id=%q command_id=%v command_type=%v\n", machineCode, requestID, command["id"], command["type"])
	return nil
}

// ackAgentWSCommand persists an ACK only for the currently pending command.
// Duplicate ACKs are accepted only when the prior result has the same command ID.
func (a *App) ackAgentWSCommand(machineCode, commandID, status, message, config string) error {
	if strings.TrimSpace(commandID) == "" || (status != "success" && status != "failed") || len(message) > 2048 {
		return fmt.Errorf("命令 ID、状态或结果消息无效")
	}
	// Treat Agent-provided command output as untrusted: redact credentials and
	// local filesystem paths before persisting it or publishing it to the UI.
	message = sanitizeAgentWebSocketText(message)
	if len(config) > 8<<10 { return fmt.Errorf("Agent 返回的 SmartDNS 配置超过 8 KiB") }
	_, matched, err := a.store.AckAgentCommandWithConfig(machineCode, commandID, status, message, config, time.Now().Unix())
	if err != nil {
		return fmt.Errorf("原子保存命令结果失败: %w", err)
	}
	if !matched {
		return fmt.Errorf("命令已被替换或不存在")
	}
	fmt.Printf("agent_ws: command ack persisted machine_code=%q command_id=%q status=%q message=%q\n", machineCode, commandID, status, message)
	a.publishBrowserEvent(map[string]any{"type": "agent.command.updated", "machine_code": machineCode, "command_id": commandID, "status": status, "message": message, "at": time.Now().Unix()})
	return nil
}
