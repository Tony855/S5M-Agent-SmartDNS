package app

import (
	"fmt"
	"net"
	"net/netip"
	"sort"
	"strings"
)

// Keep generated per-client configuration within the Agent's validated
// SmartDNS file and command-journal payload limit.
const smartDNSAgentConfigMaxBytes = 8 << 10

// buildSmartDNSPerClientConfig renders the SmartDNS half of the per-client
// routing plan. It consumes the exact listener assignments produced for
// Mihomo; it must never allocate ports or infer proxy mappings independently.
//
// The generated resolver binds only to loopback. Each client CIDR selects a
// dedicated SmartDNS group, whose encrypted upstreams use the matching named
// loopback SOCKS5 proxy. Unmatched clients have no configured default upstream.
func buildSmartDNSPerClientConfig(mappings []SmartDNSClientRuntimeMapping) (string, error) {
	return buildSmartDNSPerClientConfigInternal(mappings, "", "", false)
}

// buildSmartDNSPerClientConfigWithIngress adds dedicated LAN-facing UDP/TCP
// listeners only for addresses supplied by a separately attested host ingress
// contract. Empty addresses preserve the existing loopback-only lab output.
func buildSmartDNSPerClientConfigWithIngress(mappings []SmartDNSClientRuntimeMapping, ingressIPv4, ingressIPv6 string) (string, error) {
	return buildSmartDNSPerClientConfigInternal(mappings, ingressIPv4, ingressIPv6, true)
}

func buildSmartDNSPerClientConfigInternal(mappings []SmartDNSClientRuntimeMapping, ingressIPv4, ingressIPv6 string, requireIngress bool) (string, error) {
	if len(mappings) == 0 {
		return "", fmt.Errorf("SmartDNS per-client 运行时映射不能为空")
	}
	ordered := append([]SmartDNSClientRuntimeMapping(nil), mappings...)
	sort.Slice(ordered, func(i, j int) bool {
		return ordered[i].ClientCIDR < ordered[j].ClientCIDR
	})

	hasIPv4, hasIPv6 := false, false
	for _, mapping := range ordered {
		prefix, err := netip.ParsePrefix(strings.TrimSpace(mapping.ClientCIDR))
		if err != nil {
			return "", fmt.Errorf("SmartDNS 客户端 CIDR %q 无效: %w", mapping.ClientCIDR, err)
		}
		if prefix.String() != mapping.ClientCIDR || prefix != prefix.Masked() {
			return "", fmt.Errorf("SmartDNS 客户端 CIDR %q 必须使用规范网段表示", mapping.ClientCIDR)
		}
		prefix = prefix.Masked()
		if prefix.Bits() == 0 || !prefix.Addr().IsGlobalUnicast() || prefix.Addr().IsUnspecified() || prefix.Addr().IsLoopback() || prefix.Addr().IsLinkLocalUnicast() || prefix.Addr().IsMulticast() || prefix.Addr().Is4In6() {
			return "", fmt.Errorf("SmartDNS 客户端 CIDR %q 过宽或使用保留地址族", mapping.ClientCIDR)
		}
		if prefix.Addr().Is4() { hasIPv4 = true } else { hasIPv6 = true }
	}
	validateIngress := func(raw string, wantIPv4 bool) (netip.Addr, error) {
		ip, err := netip.ParseAddr(strings.TrimSpace(raw))
		if err != nil || ip.String() != raw || !ip.IsGlobalUnicast() || ip.IsUnspecified() || ip.IsLoopback() || ip.Zone() != "" || ip.Is4In6() || ip.IsMulticast() ||
			ip.IsLinkLocalUnicast() || ip.IsLinkLocalMulticast() || ip.Is4() != wantIPv4 {
			family := 6
			if wantIPv4 { family = 4 }
			return netip.Addr{}, fmt.Errorf("ingress 地址不是可用的 IPv%d 单播地址", family)
		}
		return ip, nil
	}
	var ipv4, ipv6 netip.Addr
	ingressRequested := requireIngress
	if hasIPv4 && strings.TrimSpace(ingressIPv4) != "" {
		var err error
		ipv4, err = validateIngress(ingressIPv4, true)
		if err != nil { return "", err }
	} else if !hasIPv4 && strings.TrimSpace(ingressIPv4) != "" {
		return "", fmt.Errorf("没有 IPv4 客户端 CIDR，不能配置 IPv4 ingress 地址")
	} else if hasIPv4 && ingressRequested {
		return "", fmt.Errorf("存在 IPv4 客户端 CIDR，但缺少已验收的 IPv4 ingress 地址")
	}
	if hasIPv6 && strings.TrimSpace(ingressIPv6) != "" {
		var err error
		ipv6, err = validateIngress(ingressIPv6, false)
		if err != nil { return "", err }
	} else if !hasIPv6 && strings.TrimSpace(ingressIPv6) != "" {
		return "", fmt.Errorf("没有 IPv6 客户端 CIDR，不能配置 IPv6 ingress 地址")
	} else if hasIPv6 && ingressRequested {
		return "", fmt.Errorf("存在 IPv6 客户端 CIDR，但缺少已验收的 IPv6 ingress 地址")
	}

	var b strings.Builder
	b.WriteString("# Generated by S5M. Do not edit; managed by the Agent.\n")
	b.WriteString("bind 127.0.0.1:6053\nbind-tcp 127.0.0.1:6053\nbind [::1]:6053\nbind-tcp [::1]:6053\n")
	// Keep the independent domestic resolver contract required by Mihomo's 6054 policy.
	b.WriteString("bind 127.0.0.1:6054 -group china-dot\nbind-tcp 127.0.0.1:6054 -group china-dot\n")
	b.WriteString("server-tls 223.5.5.5:853 -host-name dns.alidns.com -tls-host-verify dns.alidns.com -group china-dot -exclude-default-group\n")
	b.WriteString("server-tls 223.6.6.6:853 -host-name dns.alidns.com -tls-host-verify dns.alidns.com -group china-dot -exclude-default-group\n")
	b.WriteString("server-tls [2400:3200::1]:853 -host-name dns.alidns.com -tls-host-verify dns.alidns.com -group china-dot -exclude-default-group\n")
	b.WriteString("server-tls [2400:3200:baba::1]:853 -host-name dns.alidns.com -tls-host-verify dns.alidns.com -group china-dot -exclude-default-group\n")
	b.WriteString("server-tls 1.12.12.12:853 -host-name dot.pub -tls-host-verify dot.pub -group china-dot -exclude-default-group\n")
	b.WriteString("server-tls 120.53.53.53:853 -host-name dot.pub -tls-host-verify dot.pub -group china-dot -exclude-default-group\n")
	if ipv4.IsValid() {
		address := net.JoinHostPort(ipv4.String(), "6055")
		fmt.Fprintf(&b, "bind %s\nbind-tcp %s\n", address, address)
	}
	if ipv6.IsValid() {
		address := net.JoinHostPort(ipv6.String(), "6055")
		fmt.Fprintf(&b, "bind %s\nbind-tcp %s\n", address, address)
	}
	b.WriteString("\n# No default upstream: clients without an explicit CIDR mapping fail closed.\n")

	seenCIDR := make(map[string]bool, len(ordered))
	seenProxy := make(map[string]bool, len(ordered))
	seenNetworks := make([]netip.Prefix, 0, len(ordered))
	for _, m := range ordered {
		prefix, err := netip.ParsePrefix(strings.TrimSpace(m.ClientCIDR))
		if err != nil {
			return "", fmt.Errorf("SmartDNS 客户端 CIDR %q 无效: %w", m.ClientCIDR, err)
		}
		prefix = prefix.Masked()
		cidr := prefix.String()
		if seenCIDR[cidr] {
			return "", fmt.Errorf("SmartDNS 客户端 CIDR %q 重复", cidr)
		}
		for _, existing := range seenNetworks {
			if prefix.Addr().Is4() == existing.Addr().Is4() &&
				(prefix.Contains(existing.Addr()) || existing.Contains(prefix.Addr())) {
				return "", fmt.Errorf("SmartDNS 客户端 CIDR 存在重叠映射: %s 与 %s", cidr, existing.String())
			}
		}
		seenNetworks = append(seenNetworks, prefix)
		seenCIDR[cidr] = true
		if m.ListenerAddress != "127.0.0.1" || m.ListenerPort < 1024 || m.ListenerPort > 65535 {
			return "", fmt.Errorf("客户端 %s 的 SOCKS 映射必须绑定 127.0.0.1 且端口在 1024-65535", cidr)
		}
		if strings.TrimSpace(m.ListenerName) == "" || strings.TrimSpace(m.ProxyName) == "" {
			return "", fmt.Errorf("客户端 %s 的 Mihomo Listener 或代理名称为空", cidr)
		}
		// The SmartDNS proxy name is derived from the exact Mihomo listener
		// identity, not independently recreated from a port. This keeps both
		// runtime components tied to the same assignment.
		expectedListenerName := fmt.Sprintf("s5m-smartdns-%d", m.ListenerPort)
		if m.ListenerName != expectedListenerName {
			return "", fmt.Errorf("客户端 %s 的 Mihomo Listener 名称与端口映射不一致", cidr)
		}
		proxyName := m.ListenerName
		groupName := fmt.Sprintf("s5m-smartdns-group-%d", m.ListenerPort)
		if seenProxy[proxyName] {
			return "", fmt.Errorf("SmartDNS SOCKS 代理名称 %q 重复", proxyName)
		}
		seenProxy[proxyName] = true
		fmt.Fprintf(&b, "proxy-server socks5://127.0.0.1:%d -name %s\n", m.ListenerPort, proxyName)
		fmt.Fprintf(&b, "server-tls 1.1.1.1:853 -host-name cloudflare-dns.com -tls-host-verify cloudflare-dns.com -group %s -proxy %s -exclude-default-group\n", groupName, proxyName)
		fmt.Fprintf(&b, "server-tls [2606:4700:4700::1111]:853 -host-name cloudflare-dns.com -tls-host-verify cloudflare-dns.com -group %s -proxy %s -exclude-default-group\n", groupName, proxyName)
		fmt.Fprintf(&b, "server-tls 8.8.8.8:853 -host-name dns.google -tls-host-verify dns.google -group %s -proxy %s -exclude-default-group\n", groupName, proxyName)
		fmt.Fprintf(&b, "server-tls [2001:4860:4860::8888]:853 -host-name dns.google -tls-host-verify dns.google -group %s -proxy %s -exclude-default-group\n", groupName, proxyName)
		fmt.Fprintf(&b, "group-begin %s\ngroup-match -client-ip %s\ngroup-end\n\n", groupName, cidr)
	}
	b.WriteString("# Preserve A and AAAA answers; allow IPv6-only domains on dual-stack resolvers.\n")
	b.WriteString("dualstack-ip-selection no\ndualstack-ip-selection-threshold 10\ndualstack-ip-allow-force-AAAA yes\n")
	b.WriteString("cache-size 16384\ncache-persist yes\ncache-file /data/smartdns.cache\ncache-checkpoint-time 3600\nprefetch-domain yes\nserve-expired yes\nlog-level info\nlog-console yes\nlog-syslog no\n")

	config := b.String()
	if len(config) > smartDNSAgentConfigMaxBytes {
		return "", fmt.Errorf("生成的 SmartDNS 按客户端配置为 %d 字节，超过 Agent 允许的 %d 字节；请减少客户端映射数量", len(config), smartDNSAgentConfigMaxBytes)
	}
	return config, nil
}
