package app

import (
	"fmt"
	"net/netip"
	"sort"
	"strings"
)

// Keep generated per-client configuration within the Agent's validated
// SmartDNS file and command-journal payload limit.
const smartDNSAgentConfigMaxBytes = 8 << 10

// buildSmartDNSPerClientConfig renders the SmartDNS half of the per-client
// routing plan. It consumes the exact listener assignments produced for
// Mihomo; it must never allocate ports or infer proxy mappings independently.
//
// The generated resolver binds only to loopback. Each client CIDR selects a
// dedicated SmartDNS group, whose encrypted upstreams use the matching named
// loopback SOCKS5 proxy. Unmatched clients have no configured default upstream.
func buildSmartDNSPerClientConfig(mappings []SmartDNSClientRuntimeMapping) (string, error) {
	if len(mappings) == 0 {
		return "", fmt.Errorf("SmartDNS per-client 运行时映射不能为空")
	}
	ordered := append([]SmartDNSClientRuntimeMapping(nil), mappings...)
	sort.Slice(ordered, func(i, j int) bool {
		return ordered[i].ClientCIDR < ordered[j].ClientCIDR
	})

	var b strings.Builder
	b.WriteString("# Generated by S5M. Do not edit; managed by the Agent.\n")
	b.WriteString("bind 127.0.0.1:6053\nbind-tcp 127.0.0.1:6053\nbind [::1]:6053\nbind-tcp [::1]:6053\n\n")
	b.WriteString("# No default upstream: clients without an explicit CIDR mapping fail closed.\n")

	seenCIDR := make(map[string]bool, len(ordered))
	seenProxy := make(map[string]bool, len(ordered))
	for _, m := range ordered {
		prefix, err := netip.ParsePrefix(strings.TrimSpace(m.ClientCIDR))
		if err != nil {
			return "", fmt.Errorf("SmartDNS 客户端 CIDR %q 无效: %w", m.ClientCIDR, err)
		}
		cidr := prefix.Masked().String()
		if seenCIDR[cidr] {
			return "", fmt.Errorf("SmartDNS 客户端 CIDR %q 重复", cidr)
		}
		seenCIDR[cidr] = true
		if m.ListenerAddress != "127.0.0.1" || m.ListenerPort < 1024 || m.ListenerPort > 65535 {
			return "", fmt.Errorf("客户端 %s 的 SOCKS 映射必须绑定 127.0.0.1 且端口在 1024-65535", cidr)
		}
		if strings.TrimSpace(m.ListenerName) == "" || strings.TrimSpace(m.ProxyName) == "" {
			return "", fmt.Errorf("客户端 %s 的 Mihomo Listener 或代理名称为空", cidr)
		}
		// The SmartDNS proxy name is derived from the exact Mihomo listener
		// identity, not independently recreated from a port. This keeps both
		// runtime components tied to the same assignment.
		expectedListenerName := fmt.Sprintf("s5m-smartdns-%d", m.ListenerPort)
		if m.ListenerName != expectedListenerName {
			return "", fmt.Errorf("客户端 %s 的 Mihomo Listener 名称与端口映射不一致", cidr)
		}
		proxyName := m.ListenerName
		groupName := fmt.Sprintf("s5m-smartdns-group-%d", m.ListenerPort)
		if seenProxy[proxyName] {
			return "", fmt.Errorf("SmartDNS SOCKS 代理名称 %q 重复", proxyName)
		}
		seenProxy[proxyName] = true
		fmt.Fprintf(&b, "proxy-server socks5://127.0.0.1:%d -name %s\n", m.ListenerPort, proxyName)
		fmt.Fprintf(&b, "server-tls 1.1.1.1:853 -host-name cloudflare-dns.com -tls-host-verify cloudflare-dns.com -group %s -proxy %s\n", groupName, proxyName)
		fmt.Fprintf(&b, "server-tls [2606:4700:4700::1111]:853 -host-name cloudflare-dns.com -tls-host-verify cloudflare-dns.com -group %s -proxy %s\n", groupName, proxyName)
		fmt.Fprintf(&b, "server-tls 8.8.8.8:853 -host-name dns.google -tls-host-verify dns.google -group %s -proxy %s\n", groupName, proxyName)
		fmt.Fprintf(&b, "server-tls [2001:4860:4860::8888]:853 -host-name dns.google -tls-host-verify dns.google -group %s -proxy %s\n", groupName, proxyName)
		fmt.Fprintf(&b, "group-match -client-ip %s -g %s\n\n", cidr, groupName)
	}
	b.WriteString("# Preserve A and AAAA answers; allow IPv6-only domains on dual-stack resolvers.\n")
	b.WriteString("dualstack-ip-selection no\ndualstack-ip-selection-threshold 10\ndualstack-ip-allow-force-AAAA yes\n")
	b.WriteString("cache-size 16384\nprefetch-domain yes\nserve-expired yes\nlog-level info\nlog-console yes\nlog-syslog no\n")

	config := b.String()
	if len(config) > smartDNSAgentConfigMaxBytes {
		return "", fmt.Errorf("生成的 SmartDNS 按客户端配置为 %d 字节，超过 Agent 允许的 %d 字节；请减少客户端映射数量", len(config), smartDNSAgentConfigMaxBytes)
	}
	return config, nil
}
